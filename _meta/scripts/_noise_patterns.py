from __future__ import annotations

import re

# ============================================================
# A1 R1 / B1 — 标题命中 → not_policy_related (R1) 或 入口跳过
# ============================================================

JUNK_TITLE_REGEXES: list[tuple[re.Pattern, str]] = [
    # 化工/油气 + 行情/价格语义
    (
        re.compile(
            r"(原油|汽油|柴油|液化气|LNG|LPG|甲醇|乙烯|丙烯|纯碱|磷酸|PVC|烧碱|聚乙烯|聚丙烯)"
            r".{0,8}(价格|行情|走势|预测|分析|涨跌|早报|日评)"
        ),
        "化工油气行情",
    ),
    # 价格/指数(行情口径,非政策口径)
    (
        re.compile(r"每日价格|周价格|月价格|价格指数|价格预测"),
        "价格行情",
    ),
    # 周期性数据报告(月报/快报/简报/动态/观察 — 行情类)
    # 注意:必须前置「月/半月/周/季/季度/月度/周度」修饰,避免误伤"年报告"类政策
    (
        re.compile(r"(月|半月|周|季|季度|月度|周度).{0,4}(报告|快报|简报|动态|观察)"),
        "周期数据报告",
    ),
    # 库存/产销
    (
        re.compile(r"库存(周|月)?报|产销(快|月|周)报"),
        "库存产销",
    ),
    # 订单/招投标/拍卖(商业行为非政策)
    (
        re.compile(r"订单|中标|开标|流标|废标|拍卖|竞价|挂牌交易"),
        "商业订单招投标",
    ),
    # 行业新闻:项目清单/集采/揭榜/优选结果/签约(2026-04-29 用户加,扩 R1 拉行业新闻)
    (
        re.compile(
            r"项目清单(公示)?|集采.{0,4}(揭榜|结果)?|揭榜|"
            r"优选(结果|名单)(公示)?|候选企业(名单)?(公示)?|"
            r"签署.{0,8}(协议|合同|备忘录|框架)|战略合作(协议|签约)"
        ),
        "行业新闻(项目清单/集采/签约)",
    ),
    # 法律新闻(诉讼/制裁,非政策法规)
    (
        re.compile(r"破产|诉讼|欧盟.{0,6}制裁|UFLPA|海关.{0,6}查处|ESG.{0,4}(报告|评级)"),
        "法律新闻",
    ),
]


def junk_title_bucket(title: str) -> str | None:
    """标题命中 JUNK_TITLE_REGEXES 任一 → 返回 bucket 名;否则 None。"""
    if not title:
        return None
    for pat, name in JUNK_TITLE_REGEXES:
        if pat.search(title):
            return name
    return None


